insert into public.sb2_book_editions(
    book_id,format_code,status,publication_date,source_system,external_id,notes
)
select b.id,'ebook',
       case when b.status='published' then 'published' else 'unpublished' end,
       case when b.status='published' then b.publication_date else null end,
       'legacy_db','ebook:' || b.external_id,'Edizione creata durante l’importazione dello storico'
  from public.sb2_books b
  join public.sb2_author_profiles a on a.id=b.author_profile_id and upper(a.code)='FLAVIO'
 where b.source_system='legacy_db'
   and b.external_id is not null
   and not exists (
       select 1 from public.sb2_book_editions e
        where e.book_id=b.id and e.format_code='ebook'
   );

