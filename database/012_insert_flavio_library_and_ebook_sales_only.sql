-- Aggiorna un eventuale libro già presente con lo stesso titolo, senza
-- sovrascrivere i contenuti compilati successivamente nell'applicazione.
update public.sb2_books b
   set external_id=coalesce(b.external_id,x.external_id),
       source_system=case when b.external_id is null then 'legacy_db' else b.source_system end,
       synopsis=coalesce(nullif(b.synopsis,''),x.synopsis),
       publication_date=coalesce(b.publication_date,x.publication_date),
       publication_date_precision=case
           when b.publication_date is null then x.publication_date_precision
           else b.publication_date_precision
       end,
       promotion_status=coalesce(b.promotion_status,'none'),
       updated_at=now()
  from public.sb2_stage_legacy_books x
  join public.sb2_author_profiles a on upper(a.code)='FLAVIO' and a.is_active=true
 where b.author_profile_id=a.id
   and lower(b.title)=lower(x.title);

insert into public.sb2_books(
    author_profile_id,code,title,status,publication_date,synopsis,
    promotion_status,source_system,external_id,publication_date_precision
)
select a.id,x.code,x.title,x.status,x.publication_date,x.synopsis,
       'none','legacy_db',x.external_id,x.publication_date_precision
  from public.sb2_stage_legacy_books x
  join public.sb2_author_profiles a on upper(a.code)='FLAVIO' and a.is_active=true
 where not exists (
     select 1 from public.sb2_books b
      where b.author_profile_id=a.id
        and (b.external_id=x.external_id or lower(b.title)=lower(x.title))
 );

