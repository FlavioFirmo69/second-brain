select a.user_id,b.id,e.id,s.sale_date,s.quantity,'Storico ebook',
       'Importazione mensile dal database precedente',
       'legacy_db','ebook:' || s.book_external_id || ':' || to_char(s.sale_date,'YYYY-MM-DD'),now()
  from public.sb2_stage_legacy_ebook_sales s
  join public.sb2_books b
    on b.source_system='legacy_db' and b.external_id=s.book_external_id
  join public.sb2_author_profiles a on a.id=b.author_profile_id and upper(a.code)='FLAVIO'
  join public.sb2_book_editions e on e.book_id=b.id and e.format_code='ebook'
on conflict (source_system,external_id) do update
    set book_id=excluded.book_id,
        edition_id=excluded.edition_id,
        sale_date=excluded.sale_date,
        quantity=excluded.quantity,
        channel=excluded.channel,
        notes=excluded.notes,
        imported_at=now();

commit;

select count(*) as libri_legacy_flavio
  from public.sb2_books b
  join public.sb2_author_profiles a on a.id=b.author_profile_id
 where upper(a.code)='FLAVIO' and b.source_system='legacy_db';

select count(*) as periodi_vendita_ebook,
       coalesce(sum(quantity),0) as copie_ebook_importate
  from public.sb2_sales
 where source_system='legacy_db'
   and external_id like 'ebook:%';
